#include "GPIO.h"

/**
 * @brief GPIO初始化
 * @param none
 * @return none
 * @attention none
 */
void GPIO_Init(void){	
	gpio_init(Serial_PORT, GPIO_MODE_AF_PP, GPIO_OSPEED_50MHZ, Serial_TX_PIN);  	  //PB10(TX)配置为复用推挽输出
	gpio_init(Serial_PORT, GPIO_MODE_IN_FLOATING, GPIO_OSPEED_50MHZ, Serial_RX_PIN);  //PB11(RX)配置为浮空输入

	gpio_init(CAN_PORT, GPIO_MODE_AF_PP, GPIO_OSPEED_50MHZ, CAN_TX_PIN); //PA12(CAN_RX)配置为上拉输入
	gpio_init(CAN_PORT, GPIO_MODE_IPU, GPIO_OSPEED_50MHZ, Serial_RX_PIN);   //PA11(CAN_TX)配置为复用推挽输出
	
	gpio_init(PWM_PORT, GPIO_MODE_AF_PP, GPIO_OSPEED_50MHZ, PWM_PHASE_A_PIN);
    gpio_init(PWM_PORT, GPIO_MODE_AF_PP, GPIO_OSPEED_50MHZ, PWM_PHASE_B_PIN);
    gpio_init(PWM_PORT, GPIO_MODE_AF_PP, GPIO_OSPEED_50MHZ, PWM_PHASE_C_PIN);	
	
	gpio_init(ADC0_PORT, GPIO_MODE_AIN, GPIO_OSPEED_50MHZ, ADC0_IN0_PIN);     //PA0(ADC0_IN0)配置为模拟输入
	gpio_init(ADC0_PORT, GPIO_MODE_AIN, GPIO_OSPEED_50MHZ, ADC0_IN1_PIN);     //PA1(ADC0_IN1)配置为模拟输入
	gpio_init(ADC0_PORT, GPIO_MODE_AIN, GPIO_OSPEED_50MHZ, ADC0_IN2_PIN);     //PA2(ADC0_IN2)配置为模拟输入
	gpio_init(ADC0_PORT, GPIO_MODE_AIN, GPIO_OSPEED_50MHZ, ADC0_IN3_PIN);     //PA3(ADC0_IN3)配置为模拟输入
	
	gpio_init(ENC_CS_PORT, GPIO_MODE_OUT_PP, GPIO_OSPEED_50MHZ, ENC_CS_PIN);
	gpio_init(ENC_SCK_PORT, GPIO_MODE_AF_PP, GPIO_OSPEED_50MHZ, ENC_SCK_PIN);
	gpio_init(ENC_MISO_PORT, GPIO_MODE_IN_FLOATING, GPIO_OSPEED_50MHZ, ENC_MISO_PIN);
	gpio_init(ENC_MOSI_PORT, GPIO_MODE_AF_PP, GPIO_OSPEED_50MHZ, ENC_MOSI_PIN);
	
	gpio_init(DRV_CS_PORT, GPIO_MODE_OUT_PP, GPIO_OSPEED_50MHZ, DRV_CS_PIN);
	gpio_init(DRV_SCK_PORT, GPIO_MODE_AF_PP, GPIO_OSPEED_50MHZ, DRV_SCK_PIN);
	gpio_init(DRV_MISO_PORT, GPIO_MODE_IN_FLOATING, GPIO_OSPEED_50MHZ, DRV_MISO_PIN);
	gpio_init(DRV_MOSI_PORT, GPIO_MODE_AF_PP, GPIO_OSPEED_50MHZ, DRV_MOSI_PIN);
	
	gpio_init(DRV_EN_PORT,GPIO_MODE_OUT_PP,GPIO_OSPEED_50MHZ,DRV_EN_PIN);//DRV_EN配置为推挽输出
	gpio_init(DRV_nFAULT_PORT,GPIO_MODE_IN_FLOATING, GPIO_OSPEED_50MHZ, DRV_nFAULT_PIN);//DRV_nFAULT设置为悬空输入
	
	gpio_init(WS2812B_PORT, GPIO_MODE_AF_PP, GPIO_OSPEED_50MHZ, WS2812B_PIN);   //WS2812B,PB8配置为复用推挽输出
}
